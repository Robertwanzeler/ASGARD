def rows_for_subset_by_round(case: TrainingCase) -> tuple[list[dict], list[int]]:
    round_summary_path = case.scenario_dir / "round_summary.csv"
    if not round_summary_path.exists():
        raise FileNotFoundError(f"round summary not found for scenario {case.scenario}: {round_summary_path}")

    round_rows = read_round_summary(round_summary_path)
    subset_rows: list[dict] = []
    contributing_rounds: list[int] = []
    remaining = case.subset_size
    for round_entry in round_rows:
        if remaining <= 0:
            break
        round_dataset_path = Path(round_entry["dataset_path"])
        if not round_dataset_path.exists():
            continue
        rows = read_csv_rows(round_dataset_path)
        if not rows:
            continue
        take = min(remaining, len(rows))
        subset_rows.extend(rows[:take])
        contributing_rounds.append(int(round_entry["round"]))
        remaining -= take

    if len(subset_rows) != case.subset_size:
        raise SystemExit(
            f"unable to reconstruct subset rows by rounds for {case.scenario} subset {case.subset_size}: "
            f"expected {case.subset_size}, got {len(subset_rows)}"
        )
    return subset_rows, contributing_rounds


def subset_rows_with_boundaries(case: TrainingCase) -> tuple[list[dict], list[int], list[tuple[int, int, int]]]:
    round_summary = read_round_summary(case.scenario_dir / "round_summary.csv")
    subset_rows: list[dict] = []
    contributing_rounds: list[int] = []
    boundaries: list[tuple[int, int, int]] = []
    remaining = case.subset_size
    offset = 0
    for round_entry in round_summary:
        if remaining <= 0:
            break
        round_dataset_path = Path(round_entry["dataset_path"])
        if not round_dataset_path.exists():
            continue
        rows = read_csv_rows(round_dataset_path)
        if not rows:
            continue
        take = min(remaining, len(rows))
        subset_rows.extend(rows[:take])
        round_number = int(round_entry["round"])
        contributing_rounds.append(round_number)
        boundaries.append((round_number, offset, offset + take))
        offset += take
        remaining -= take
    if len(subset_rows) != case.subset_size:
        raise SystemExit(
            f"unable to reconstruct subset rows by rounds for {case.scenario} subset {case.subset_size}: "
            f"expected {case.subset_size}, got {len(subset_rows)}"
        )
    return subset_rows, contributing_rounds, boundaries


def build_round_split(
    case: TrainingCase,
    test_round_fraction: float,
    min_test_rounds: int,
) -> RoundSplit:
    subset_rows, contributing_rounds, round_boundaries = subset_rows_with_boundaries(case)
    if len(contributing_rounds) < 2:
        raise SystemExit(
            f"round-based split requires at least 2 contributing rounds for {case.scenario} subset {case.subset_size}"
        )

    requested_test_rounds = max(min_test_rounds, int(math.ceil(len(contributing_rounds) * test_round_fraction)))
    num_test_rounds = min(len(contributing_rounds) - 1, requested_test_rounds)
    train_rounds = contributing_rounds[:-num_test_rounds]
    test_rounds = contributing_rounds[-num_test_rounds:]
    train_rows: list[dict[str, Any]] = []
    test_rows: list[dict[str, Any]] = []

    for round_number, start, end in round_boundaries:
        rows = subset_rows[start:end]
        if round_number in train_rounds:
            train_rows.extend(rows)
        elif round_number in test_rounds:
            test_rows.extend(rows)

    if not train_rows or not test_rows:
        raise SystemExit(
            f"round-based split produced an empty partition for {case.scenario} subset {case.subset_size}: "
            f"train_rounds={train_rounds}, test_rounds={test_rounds}"
        )

    return RoundSplit(
        mode="round_holdout",
        train_rows=train_rows,
        test_rows=test_rows,
        train_rounds=train_rounds,
        test_rounds=test_rounds,
        contributing_rounds=contributing_rounds,
    )


def build_manual_round_split(
    case: TrainingCase,
    train_rounds: list[int],
    test_rounds: list[int],
) -> RoundSplit:
    subset_rows, contributing_rounds, round_boundaries = subset_rows_with_boundaries(case)
    contributing_set = set(contributing_rounds)
    train_set = set(train_rounds)
    test_set = set(test_rounds)

    unknown = sorted((train_set | test_set) - contributing_set)
    if unknown:
        raise SystemExit(
            f"manual round split for {case.scenario} subset {case.subset_size} references rounds not present "
            f"in the subset: {unknown}; contributing rounds are {contributing_rounds}"
        )
    if not train_set or not test_set:
        raise SystemExit("manual round split requires non-empty --train-rounds and --test-rounds")
    if train_set & test_set:
        raise SystemExit(f"manual round split has overlapping train/test rounds: {sorted(train_set & test_set)}")

    selected = train_set | test_set
    train_rows: list[dict[str, Any]] = []
    test_rows: list[dict[str, Any]] = []
    selected_rounds: list[int] = []
    for round_number, start, end in round_boundaries:
        if round_number not in selected:
            continue
        selected_rounds.append(round_number)
        rows = subset_rows[start:end]
        if round_number in train_set:
            train_rows.extend(rows)
        elif round_number in test_set:
            test_rows.extend(rows)

    if not train_rows or not test_rows:
        raise SystemExit(
            f"manual round split produced an empty partition for {case.scenario} subset {case.subset_size}: "
            f"train_rounds={sorted(train_set)}, test_rounds={sorted(test_set)}"
        )

    return RoundSplit(
        mode="manual_round_split",
        train_rows=train_rows,
        test_rows=test_rows,
        train_rounds=sorted(train_set),
        test_rounds=sorted(test_set),
        contributing_rounds=selected_rounds,
    )


def build_direct_row_split(
    rows: list[dict],
    test_fraction: float,
    min_test_rows: int,
) -> RoundSplit:
    if len(rows) < 2:
        raise SystemExit("direct dataset split requires at least 2 rows")
    if not (0.0 < float(test_fraction) < 1.0):
        raise SystemExit("--direct-test-fraction must be between 0 and 1")

    requested_test_rows = max(int(math.ceil(len(rows) * float(test_fraction))), int(min_test_rows))
    num_test_rows = min(len(rows) - 1, requested_test_rows)
    split_at = len(rows) - num_test_rows
    train_rows = rows[:split_at]
    test_rows = rows[split_at:]

    if not train_rows or not test_rows:
        raise SystemExit(
            f"direct dataset split produced an empty partition: train_rows={len(train_rows)}, test_rows={len(test_rows)}"
        )

    return RoundSplit(
        mode="direct_row_holdout",
        train_rows=train_rows,
        test_rows=test_rows,
        train_rounds=[],
        test_rounds=[],
        contributing_rounds=[],
    )


class DenseGraphSAGELayer(nn.Module):
    def __init__(self, in_dim: int, out_dim: int) -> None:
        super().__init__()
        self.self_linear = nn.Linear(in_dim, out_dim)
        self.neigh_linear = nn.Linear(in_dim, out_dim)

    def forward(self, x: torch.Tensor, support: torch.Tensor) -> torch.Tensor:
        degree = support.sum(dim=1, keepdim=True).clamp(min=1.0)
        neigh = support @ x / degree
        return self.self_linear(x) + self.neigh_linear(neigh)


class GraphSAGEReconstructor(nn.Module):
    def __init__(self, in_dim: int, hidden_dim: int, embed_dim: int, dropout: float) -> None:
        super().__init__()
        self.sage1 = DenseGraphSAGELayer(in_dim, hidden_dim)
        self.sage2 = DenseGraphSAGELayer(hidden_dim, embed_dim)
        self.dropout = dropout
        decoder_dim = embed_dim * 4
        self.decoder = nn.Sequential(
            nn.Linear(decoder_dim, hidden_dim),
            nn.ReLU(),
            nn.Dropout(dropout),
            nn.Linear(hidden_dim, 1),
        )

    def encode(self, x: torch.Tensor, support: torch.Tensor) -> torch.Tensor:
        hidden = self.sage1(x, support)
        hidden = F.relu(hidden)
        hidden = F.dropout(hidden, p=self.dropout, training=self.training)
        embedding = self.sage2(hidden, support)
        return F.normalize(embedding, p=2, dim=1)

    def decode(self, embedding: torch.Tensor) -> torch.Tensor:
        n_nodes = embedding.shape[0]
        src = embedding.unsqueeze(1).expand(n_nodes, n_nodes, -1)
        dst = embedding.unsqueeze(0).expand(n_nodes, n_nodes, -1)
        pair_features = torch.cat([src, dst, torch.abs(src - dst), src * dst], dim=-1)
        logits = self.decoder(pair_features).squeeze(-1)
        return logits

    def forward(self, x: torch.Tensor, support: torch.Tensor) -> tuple[torch.Tensor, torch.Tensor]:
        embedding = self.encode(x, support)
        return embedding, self.decode(embedding)


def compute_metrics(logits: torch.Tensor, target: torch.Tensor, threshold: float) -> dict:
    mask = ~torch.eye(target.shape[0], dtype=torch.bool, device=target.device)
    probs = torch.sigmoid(logits)
    pred = (probs >= threshold).float()
    target_masked = target[mask]
    pred_masked = pred[mask]

    tp = int(((pred_masked == 1) & (target_masked == 1)).sum().item())
    fp = int(((pred_masked == 1) & (target_masked == 0)).sum().item())
    fn = int(((pred_masked == 0) & (target_masked == 1)).sum().item())
    tn = int(((pred_masked == 0) & (target_masked == 0)).sum().item())
    precision = tp / (tp + fp) if (tp + fp) else 0.0
    recall = tp / (tp + fn) if (tp + fn) else 0.0
    f1 = (2.0 * precision * recall / (precision + recall)) if (precision + recall) else 0.0

    return {
        "threshold": threshold,
        "tp": tp,
        "fp": fp,
        "fn": fn,
        "tn": tn,
        "precision": round(precision, 6),
        "recall": round(recall, 6),
        "f1": round(f1, 6),
        "predicted_edges": int(pred_masked.sum().item()),
        "target_edges": int(target_masked.sum().item()),
    }


def top_edges(
    logits: torch.Tensor,
    node_ids: list[str],
    target_graph: dict,
    threshold: float,
) -> list[dict]:
    truth = {
        (edge.get("source"), edge.get("target")): edge.get("relation", "unknown")
        for edge in target_graph.get("edges", [])
    }
    probs = torch.sigmoid(logits).detach().cpu()
    edges = []
    for src_idx, source in enumerate(node_ids):
        for dst_idx, target in enumerate(node_ids):
            if src_idx == dst_idx:
                continue
            score = float(probs[src_idx, dst_idx].item())
            if score < threshold:
                continue
            edges.append(
                {
                    "source": source,
                    "target": target,
                    "score": round(score, 6),
                    "baseline_relation": truth.get((source, target)),
                    "is_true_edge": (source, target) in truth,
                }
            )
    edges.sort(key=lambda item: (-item["score"], item["source"], item["target"]))
    return edges


def train_case(
    case: TrainingCase,
    direct_mode: bool,
    epochs: tuple[int, ...],
    hidden_dim: int,
    embed_dim: int,
    dropout: float,
    learning_rate: float,
    weight_decay: float,
    threshold: float,
    seed: int,
    split_by_rounds: bool,
    test_round_fraction: float,
    min_test_rounds: int,
    manual_train_rounds: list[int] | None,
    manual_test_rounds: list[int] | None,
    direct_test_fraction: float,
    direct_min_test_rows: int,
) -> dict:
    set_seed(seed)
    ensure_dir(case.output_dir)

    split = None
    if manual_train_rounds or manual_test_rounds:
        if not (manual_train_rounds and manual_test_rounds):
            raise SystemExit("manual round split requires both --train-rounds and --test-rounds")
        split = build_manual_round_split(case, manual_train_rounds, manual_test_rounds)
    elif split_by_rounds:
        split = build_round_split(case, test_round_fraction, min_test_rounds)
    elif direct_mode:
        if direct_test_fraction > 0:
            split = build_direct_row_split(read_csv_rows(case.dataset_path), direct_test_fraction, direct_min_test_rows)

    if split is not None:
        rows = split.train_rows + split.test_rows
        combined_graph = build_graph_from_rows(rows)
        train_graph = build_graph_from_rows(split.train_rows)
        eval_graph = build_graph_from_rows(split.test_rows)
        node_ids = [node["id"] for node in combined_graph.get("nodes", [])]
        node_index = {node_id: idx for idx, node_id in enumerate(node_ids)}
        train_support = build_support_matrix(split.train_rows, node_index)
        test_support = build_support_matrix(split.test_rows, node_index)
        train_raw = build_feature_matrix(train_graph, split.train_rows, node_ids, node_index, train_support)
        train_features, feature_mean, feature_std = normalize_features(train_raw)
        test_raw = build_feature_matrix(eval_graph, split.test_rows, node_ids, node_index, test_support)
        test_features, _, _ = normalize_features(test_raw, mean=feature_mean, std=feature_std)
        train_target = build_target_adjacency(train_graph, node_ids, node_index)
        eval_target = build_target_adjacency(eval_graph, node_ids, node_index)
        train_rows = split.train_rows
        test_rows = split.test_rows
    else:
        rows = read_csv_rows(case.dataset_path)
        graph = build_graph_from_rows(rows)
        _, rows, node_ids, train_features, train_support, train_target = tensors_from_rows(graph, rows)
        train_rows = rows
        test_rows = []
        test_features = None
        test_support = None
        eval_target = train_target
        eval_graph = graph

    device = torch.device("cuda" if torch.cuda.is_available() else "cpu")
    train_features = train_features.to(device)
    train_support = train_support.to(device)
    train_target = train_target.to(device)
    eval_target = eval_target.to(device)
    if test_features is not None and test_support is not None:
        test_features = test_features.to(device)
        test_support = test_support.to(device)

    model = GraphSAGEReconstructor(
        in_dim=train_features.shape[1],
        hidden_dim=hidden_dim,
        embed_dim=embed_dim,
        dropout=dropout,
    ).to(device)
    optimizer = torch.optim.Adam(
        model.parameters(),
        lr=learning_rate,
        weight_decay=weight_decay,
    )

    max_epoch = max(epochs)
    train_mask = ~torch.eye(train_target.shape[0], dtype=torch.bool, device=device)
    positives = float(train_target[train_mask].sum().item())
    negatives = float(train_mask.sum().item() - positives)
    pos_weight = torch.tensor(
        [negatives / max(positives, 1.0)],
        dtype=torch.float32,
        device=device,
    )
    criterion = nn.BCEWithLogitsLoss(pos_weight=pos_weight)

    checkpoints = set(epochs)
    history = []
    best = None
    best_f1 = -1.0
    started_at = time.time()
    checkpoint_dir = case.output_dir / "checkpoints"
    checkpoint_dir.mkdir(parents=True, exist_ok=True)

    for epoch in range(1, max_epoch + 1):
        model.train()
        optimizer.zero_grad()
        _, train_logits = model(train_features, train_support)
        loss = criterion(train_logits[train_mask], train_target[train_mask])
        loss.backward()
        optimizer.step()

        if epoch not in checkpoints:
            continue

        model.eval()
        with torch.no_grad():
            train_embedding, train_logits = model(train_features, train_support)
            train_metrics = compute_metrics(train_logits, train_target, threshold)
            eval_embedding = train_embedding
            eval_logits = train_logits
            eval_metrics = train_metrics
            if test_features is not None and test_support is not None:
                eval_embedding, eval_logits = model(test_features, test_support)
                eval_metrics = compute_metrics(eval_logits, eval_target, threshold)
            snapshot = {
                "epoch": epoch,
                "loss": round(float(loss.item()), 6),
                **eval_metrics,
                "train_precision": train_metrics["precision"],
                "train_recall": train_metrics["recall"],
                "train_f1": train_metrics["f1"],
                "train_tp": train_metrics["tp"],
                "train_fp": train_metrics["fp"],
                "train_fn": train_metrics["fn"],
                "train_tn": train_metrics["tn"],
            }
            history.append(snapshot)
            torch.save(
                {
                    "state_dict": model.state_dict(),
                    "node_ids": node_ids,
                    "feature_dim": int(train_features.shape[1]),
                    "hidden_dim": hidden_dim,
                    "embed_dim": embed_dim,
                    "dropout": dropout,
                    "threshold": threshold,
                    "epoch": epoch,
                },
                checkpoint_dir / f"epoch_{epoch}.pt",
            )
            if eval_metrics["f1"] >= best_f1:
                best_f1 = eval_metrics["f1"]
                best = {
                    "epoch": epoch,
                    "metrics": eval_metrics,
                    "train_metrics": train_metrics,
                    "embedding": eval_embedding.detach().cpu(),
                    "logits": eval_logits.detach().cpu(),
                }

    best_edges = top_edges(best["logits"], node_ids, eval_graph, threshold) if best else []
    torch.save(
        {
            "state_dict": model.state_dict(),
            "node_ids": node_ids,
            "feature_dim": int(train_features.shape[1]),
            "hidden_dim": hidden_dim,
            "embed_dim": embed_dim,
            "dropout": dropout,
            "threshold": threshold,
            "best_epoch": best["epoch"] if best else None,
        },
        case.output_dir / "best_model.pt",
    )

    summary = {
        "scenario": case.scenario,
        "subset_size": case.subset_size,
        "dataset_path": str(case.dataset_path),
        "graph_path": str(case.graph_path),
        "output_dir": str(case.output_dir),
        "device": str(device),
        "rows": len(rows),
        "train_rows": len(train_rows),
        "test_rows": len(test_rows),
        "nodes": len(node_ids),
        "target_edges": int(eval_target.sum().item()),
        "train_target_edges": int(train_target.sum().item()),
        "eval_target_edges": int(eval_target.sum().item()),
        "feature_dim": int(train_features.shape[1]),
        "epochs_requested": list(epochs),
        "elapsed_seconds": round(time.time() - started_at, 3),
        "split_mode": split.mode if split else "none",
        "train_rounds": split.train_rounds if split else [],
        "test_rounds": split.test_rounds if split else [],
        "contributing_rounds": split.contributing_rounds if split else [],
        "best_epoch": best["epoch"] if best else None,
        "best_metrics": best["metrics"] if best else {},
        "train_metrics_at_best": best["train_metrics"] if best else {},
        "history": history,
        "predicted_edges_at_best": best_edges[:50],
    }
    with (case.output_dir / "training_summary.json").open("w") as f:
        json.dump(summary, f, indent=2, ensure_ascii=False)

    with (case.output_dir / "history.csv").open("w", newline="") as f:
        fieldnames = [
            "epoch",
            "loss",
            "precision",
            "recall",
            "f1",
            "tp",
            "fp",
            "fn",
            "tn",
            "predicted_edges",
            "target_edges",
            "threshold",
            "train_precision",
            "train_recall",
            "train_f1",
            "train_tp",
            "train_fp",
            "train_fn",
            "train_tn",
        ]
        writer = csv.DictWriter(f, fieldnames=fieldnames)
        writer.writeheader()
        writer.writerows(history)

    return summary


def main() -> int:
    args = parse_args()
    epochs = parse_int_tuple(args.epochs)
    subset_sizes = parse_int_tuple(args.subset_sizes)
    manual_train_rounds = parse_round_list(args.train_rounds) if args.train_rounds else None
    manual_test_rounds = parse_round_list(args.test_rounds) if args.test_rounds else None
    if (manual_train_rounds is None) != (manual_test_rounds is None):
        raise SystemExit("use both --train-rounds and --test-rounds together")

    direct_mode = bool(args.dataset_path or args.graph_path)
    if direct_mode and not (args.dataset_path and args.graph_path):
        raise SystemExit("use both --dataset-path and --graph-path together")
    if direct_mode and (args.split_by_rounds or manual_train_rounds or manual_test_rounds):
        raise SystemExit("round-based splits are not supported in direct dataset mode; use --direct-test-fraction")

    if direct_mode:
        dataset_path = Path(args.dataset_path)
        graph_path = Path(args.graph_path)
        output_root = Path(args.output_dir) if args.output_dir else dataset_path.parent / DEFAULT_OUTPUT_STEM
        ensure_dir(output_root)
        experiment_dir = dataset_path.parent
        cases = build_direct_case(dataset_path, graph_path, args.scenario_label, output_root)
    else:
        experiment_dir = Path(args.experiment_dir) if args.experiment_dir else latest_experiment_dir(DEFAULT_EXPERIMENT_ROOT)
        output_root = Path(args.output_dir) if args.output_dir else experiment_dir / DEFAULT_OUTPUT_STEM
        ensure_dir(output_root)
        reports = selected_reports(experiment_dir, args.scenarios)
        cases = build_cases(experiment_dir, reports, subset_sizes, output_root)

    aggregate = {
        "generated_at": int(time.time()),
        "generated_at_iso": time.strftime("%Y-%m-%dT%H:%M:%S"),
        "experiment_dir": str(experiment_dir),
        "output_root": str(output_root),
        "epochs": list(epochs),
        "subset_sizes": [] if direct_mode else list(subset_sizes),
        "threshold": args.threshold,
        "direct_mode": direct_mode,
        "dataset_path": args.dataset_path or "",
        "graph_path": args.graph_path or "",
        "scenario_label": args.scenario_label if direct_mode else "",
        "split_by_rounds": args.split_by_rounds,
        "test_round_fraction": args.test_round_fraction,
        "min_test_rounds": args.min_test_rounds,
        "direct_test_fraction": args.direct_test_fraction,
        "direct_min_test_rows": args.direct_min_test_rows,
        "train_rounds": manual_train_rounds or [],
        "test_rounds": manual_test_rounds or [],
        "cases": [],
    }

    print(f"Experimento de treino: {experiment_dir}")
    print(f"Saída do GraphSAGE: {output_root}")
    print(f"Epochs: {', '.join(str(value) for value in epochs)}")
    if direct_mode:
        print(f"Dataset direto: {args.dataset_path}")
        print(f"Grafo direto: {args.graph_path}")
    else:
        print(f"Subsets: {', '.join(str(value) for value in subset_sizes)}")
    if manual_train_rounds and manual_test_rounds:
        print(f"Split manual de rodadas: treino={manual_train_rounds} | teste={manual_test_rounds}")
    elif direct_mode:
        print(f"Split direto temporal: {args.direct_test_fraction:.2f} para teste")
    else:
        print(f"Split por rodadas: {'sim' if args.split_by_rounds else 'não'}")

    for case in cases:
        print(f"\n=== {case.scenario} | subset {case.subset_size} ===")
        summary = train_case(
            case=case,
            direct_mode=direct_mode,
            epochs=epochs,
            hidden_dim=args.hidden_dim,
            embed_dim=args.embed_dim,
            dropout=args.dropout,
            learning_rate=args.learning_rate,
            weight_decay=args.weight_decay,
            threshold=args.threshold,
            seed=args.seed,
            split_by_rounds=args.split_by_rounds,
            test_round_fraction=args.test_round_fraction,
            min_test_rounds=args.min_test_rounds,
            manual_train_rounds=manual_train_rounds,
            manual_test_rounds=manual_test_rounds,
            direct_test_fraction=args.direct_test_fraction,
            direct_min_test_rows=args.direct_min_test_rows,
        )
        aggregate["cases"].append(summary)
        best = summary.get("best_metrics", {})
        if summary.get("test_rows", 0) > 0:
            train_best = summary.get("train_metrics_at_best", {})
            print(
                "best_epoch={best_epoch} | test_f1={test_f1:.4f} | test_precision={test_precision:.4f} | "
                "test_recall={test_recall:.4f} | train_f1={train_f1:.4f} | "
                "train_rounds={train_rounds} | test_rounds={test_rounds}".format(
                    best_epoch=summary.get("best_epoch"),
                    test_f1=best.get("f1", 0.0),
                    test_precision=best.get("precision", 0.0),
                    test_recall=best.get("recall", 0.0),
                    train_f1=train_best.get("f1", 0.0),
                    train_rounds=summary.get("train_rounds", []),
                    test_rounds=summary.get("test_rounds", []),
                )
            )
        else:
            print(
                "best_epoch={best_epoch} | f1={f1:.4f} | precision={precision:.4f} | "
                "recall={recall:.4f}".format(
                    best_epoch=summary.get("best_epoch"),
                    f1=best.get("f1", 0.0),
                    precision=best.get("precision", 0.0),
                    recall=best.get("recall", 0.0),
                )
            )

    aggregate_path = output_root / "aggregate_report.json"
    with aggregate_path.open("w") as f:
        json.dump(aggregate, f, indent=2, ensure_ascii=False)

    print(f"\nRelatório agregado: {aggregate_path}")
    return 0



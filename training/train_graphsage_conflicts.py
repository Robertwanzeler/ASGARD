#!/usr/bin/env python3
"""
Train a GraphSAGE-style graph reconstructor on completed conflitos datasets.

This script is the first practical step after the collection protocol:

- it consumes the `50`, `150`, and `450` conflict subsets generated by
  `scripts/run_experimentos_conflitos.py`;
- it builds node features from the exported conflict CSV;
- it builds a support graph from row-level node co-occurrence;
- it trains a GraphSAGE-style encoder plus a link predictor to reconstruct the
  scenario conflict graph;
- it reports reconstruction precision/recall/F1 across an epoch sweep.

The goal is to align the GreenRAN pipeline with the next methodological step of
`conflitos`: training a graph learner after the `50/150/450` datasets have been
collected.
"""

